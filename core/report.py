"""JSON report generation.

The report only contains data produced by the scanners: no evidence is ever
synthesised here.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from enum import Enum
from typing import Any, Iterable, Sequence

from core.config import APP_NAME, VERSION
from core.models import CheckResult, Severity, Status

SCHEMA_VERSION = "1.0"

LIMITATIONS: tuple[str, ...] = (
    "Non-intrusive, point-in-time assessment of externally visible configuration; "
    "it is not a penetration test or vulnerability scan.",
    "Only https://<domain>/ and http://<domain>/ are analysed; other hosts, "
    "paths, ports and applications are out of scope.",
    "Connections use the first reachable resolved address; load-balanced or "
    "geo-distributed backends may be configured differently.",
    "TLS analysis covers certificate trust, validity period and protocol version; "
    "cipher suites, OCSP/CT and key strength are not graded.",
    "SPF is evaluated at the top level (includes are not expanded recursively); "
    "DKIM cannot be checked without knowing the selectors.",
    "Security headers are read from a single response and may differ across pages.",
    "The score is an educational indicator, not an official security rating.",
)

DISCLAIMER = (
    "Generated by CyberScore Lite for an authorised, non-intrusive assessment. "
    "Results reflect the observed state at generation time."
)

_SEVERITY_RANK = {
    Severity.CRITICAL: 0,
    Severity.HIGH: 1,
    Severity.MEDIUM: 2,
    Severity.LOW: 3,
    Severity.INFO: 4,
}


def priority_for(result: CheckResult) -> str:
    """P1 = urgent, P2 = important, P3 = hardening."""
    severe = result.severity in (Severity.CRITICAL, Severity.HIGH)
    if result.status is Status.FAIL and severe:
        return "P1"
    if result.status is Status.FAIL or severe:
        return "P2"
    return "P3"


def prioritized_recommendations(results: Iterable[CheckResult]) -> list[dict[str, Any]]:
    """Remediation items for scored FAIL/WARNING controls, most urgent first."""
    actionable = [
        r for r in results if r.status in (Status.FAIL, Status.WARNING) and r.weight > 0
    ]
    actionable.sort(
        key=lambda r: (
            priority_for(r),
            0 if r.status is Status.FAIL else 1,
            _SEVERITY_RANK[r.severity],
            -r.weight,
        )
    )
    return [
        {
            "priority": priority_for(r),
            "check_id": r.id,
            "name": r.name,
            "category": r.category.value,
            "status": r.status.value,
            "severity": r.severity.value,
            "weight": r.weight,
            "finding": r.summary,
            "risk": r.risk_explanation,
            "recommendation": r.recommendation,
        }
        for r in actionable
    ]


def _jsonable(value: Any) -> Any:
    """Recursively convert values into JSON-native types."""
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_jsonable(v) for v in value]
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, bytes):
        return value.hex()
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)


def build_report(
    domain: str,
    results: Sequence[CheckResult],
    score: dict[str, Any],
    *,
    addresses: Sequence[str] = (),
    generated_at: datetime | None = None,
    sample_data: bool = False,
) -> dict[str, Any]:
    """Assemble the full, JSON-serialisable assessment report."""
    generated_at = generated_at or datetime.now(UTC)
    not_assessed = [
        {"check_id": r.id, "name": r.name, "reason": r.summary}
        for r in results
        if r.status is Status.ERROR
    ]
    report = {
        "schema_version": SCHEMA_VERSION,
        "tool": {"name": APP_NAME, "version": VERSION},
        "assessment": {
            "domain": domain,
            "generated_at_utc": generated_at.astimezone(UTC).isoformat(
                timespec="seconds"
            ),
            "resolved_addresses": list(addresses),
            "sample_data": sample_data,
            "method": "non-intrusive (DNS queries, TLS handshakes, HTTP HEAD/GET on / only)",
        },
        "summary": score,
        "checks": [r.to_dict() for r in results],
        "recommendations": prioritized_recommendations(results),
        "not_assessed": not_assessed,
        "limitations": list(LIMITATIONS),
        "disclaimer": DISCLAIMER,
    }
    return _jsonable(report)


def report_to_json(report: dict[str, Any]) -> str:
    """Serialise a report with stable formatting."""
    return json.dumps(report, indent=2, ensure_ascii=False)
